    private fun picture(qr: QrCode) = (0 until qr.size).map { y -> (0 until qr.size).joinToString("") { x -> if (qr.isDark(x, y)) "#" else "." } }

    @Test fun matches_reference_0() = assertEquals(case0, picture(QrCode.encode("https://payup-ae6fc.web.app/g/AbCdEfGhIjKlMnOpQrSt-_", mask = 3)))
    @Test fun matches_reference_1() = assertEquals(case1, picture(QrCode.encode("A", mask = 0)))
    @Test fun matches_reference_2() = assertEquals(case2, picture(QrCode.encode("xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx", mask = 5)))

    @Test fun picks_a_mask_and_a_valid_size() {
        val qr = QrCode.encode("https://payup-ae6fc.web.app/g/AbCdEfGhIjKlMnOpQrSt-_")
        assertEquals(33, qr.size)
    }

    @Test fun too_long_text_is_refused() {
        assertFailsWith<IllegalArgumentException> { QrCode.encode("x".repeat(QrCode.MAX_BYTES + 1)) }
        QrCode.encode("x".repeat(QrCode.MAX_BYTES))
    }
